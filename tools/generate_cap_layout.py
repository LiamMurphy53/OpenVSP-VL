"""Generate the pinned arm64 cap layout from complete official Geom declarations.

Development-only: --headers is a hash-verified OpenVSP source header tree;
--eli and --eigen are the matching dependency include directories. --eli-template
is Code-Eli's cmake/code_eli.hpp.in. No engine code is linked or executed.
Unused CAD export pointer types are forward-declared, leaving Geom unchanged.
"""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import re
import subprocess
import tempfile

GEOM_SHA = '34c7959d2ceb05a59ccbaf8242022a546ab56b56e995016f88db348b7271b360'
FIELDS = ('m_CapUMinSuccess', 'm_CapUMaxSuccess', 'm_CapUMinOption',
          'm_CapUMaxOption', 'm_CapUMinTess', 'm_TessU', 'm_TessW')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for key in ('headers', 'eli', 'eigen', 'eli-template', 'output'):
        p.add_argument('--'+key, type=Path, required=True)
    a = p.parse_args()
    if (platform.system(), platform.machine()) != ('Darwin', 'arm64'):
        p.error('Generate using macOS arm64, matching the installed engine.')
    geom = a.headers/'src/geom_core/Geom.h'
    if hashlib.sha256(geom.read_bytes()).hexdigest() != GEOM_SHA:
        p.error('Geom.h does not match the pinned OpenVSP 3.52.2 source.')
    sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp/'api').mkdir(); (tmp/'eli').mkdir()
        for name in ('dll_iges.h', 'dll_entity128.h', 'dll_entity406.h'):
            (tmp/'api'/name).write_text('// Unused CAD export pointer declarations.\n')
        # Version/timestamp strings do not affect declarations or layout. Keep
        # all compiler/platform/Eigen configuration from the official template.
        (tmp/'eli/code_eli.hpp').write_text(re.sub(r'@\w+@', '0', a.eli_template.read_text()))
        source = '''#include <string>
#include <vector>
#include <iostream>
#define CADUTIL__INCLUDED_
class STEPutil; class IGESutil; class SdaiB_spline_surface_with_knots;
#include "Geom.h"
class StudioGeomLayout: public Geom { public: static void output() {
'''
        for field in FIELDS:
            source += f'std::cout << "{field} " << __builtin_offsetof(StudioGeomLayout,{field}) << "\\n";\n'
        source += 'std::cout << "size " << sizeof(Geom) << "\\n"; }};\nint main(){StudioGeomLayout::output();}\n'
        (tmp/'layout.cpp').write_text(source)
        includes = [tmp, *sorted({q.parent.resolve() for q in a.headers.rglob('*.h')}),
                    a.eli.resolve(), a.eigen.resolve(), Path(sdk)/'usr/include/libxml2']
        cmd = ['clang++', '-std=c++17', '-Wno-invalid-offsetof',
               *[x for directory in includes for x in ('-I', str(directory))],
               str(tmp/'layout.cpp'), '-o', str(tmp/'layout')]
        subprocess.run(cmd, check=True, capture_output=True, text=True)
        values = dict(line.split() for line in subprocess.check_output([str(tmp/'layout')], text=True).splitlines())
    text = '// Generated by tools/generate_cap_layout.py; do not edit.\n'
    text += '// Complete official Geom.h SHA-256: '+GEOM_SHA+'\n'
    text += '// OpenVSP commit 8782f46d4399ac04d0a1277d414246bb37035666; macOS arm64.\n'
    text += '#pragma once\n#include <cstddef>\nnamespace studio_cap_layout {\n'
    for name, value in values.items():
        text += f'inline constexpr std::size_t {name} = {int(value)};\n'
    text += '}\n'
    a.output.write_text(text)
    print(json.dumps(values, sort_keys=True))


if __name__ == '__main__':
    main()
