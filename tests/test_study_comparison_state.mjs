import assert from 'node:assert/strict';
import {studyComparisonState} from '../web/study-comparison-state.js';
const a={study:'study-A',id:'execution-A'},b={study:'study-A',id:'execution-B'};
const result=(owner,key='area')=>({...owner,field:{key},rows:[{values:[1.12345678901234,2]}]});
const state=studyComparisonState();
assert.equal(state.snapshot.phase,'idle');
state.select(a);const first=state.begin('area'),original=result(a),before=JSON.stringify(original);
assert.equal(state.resolve(first,original),true);assert.equal(state.snapshot.data,original);
const refresh=state.begin('area');
assert.equal(state.snapshot.data,original,'Refreshing the same result can keep its current plot visible');
state.select(b);
assert.equal(state.snapshot.data,null,'Selecting another execution clears old tables and exports immediately');
assert.equal(state.resolve(refresh,original),false,'An earlier execution response cannot return');
const newer=state.begin('area');state.resolve(newer,result(b));
const otherField=state.begin('length');
assert.equal(state.snapshot.data,null,'Changing fields also clears data from the old field');
assert.equal(state.resolve(newer,result(b)),false);
state.reject(otherField,Error('Temporary read failure'));
assert.equal(state.snapshot.phase,'error');assert.equal(state.snapshot.data,null);
assert.equal(state.snapshot.key,'length','A failed field selection remains available for retry');
const retry=state.begin('length');state.resolve(retry,result(b,'length'));assert.equal(state.snapshot.phase,'ready');
const slow=state.begin('length'),fast=state.begin('length');state.resolve(fast,result(b,'length'));
assert.equal(state.reject(slow,Error('Old failure')),false,'A late failed refresh cannot erase a newer result');
const mismatch=state.begin('length');state.resolve(mismatch,result(a,'length'));
assert.equal(state.snapshot.phase,'error');assert.equal(state.snapshot.data,null,'Even a current request must return the correct owner');
const wrongField=state.begin('length');state.resolve(wrongField,result(b,'area'));
assert.equal(state.snapshot.phase,'error');assert.equal(state.snapshot.data,null);
const oldStudy=state.begin('length');state.select({...b,study:'study-B'});
assert.equal(state.resolve(oldStudy,result(b,'length')),false,'Study identity matters as well as execution ID');
const missing=state.begin('area');state.empty();
assert.equal(state.snapshot.phase,'empty');assert.equal(state.resolve(missing,result({...b,study:'study-B'})),false);
state.fail(Error('Fields unavailable'));assert.equal(state.snapshot.phase,'error');assert.equal(state.snapshot.key,null);
state.select(null);assert.equal(state.snapshot.phase,'idle');assert.equal(state.snapshot.data,null);
assert.equal(JSON.stringify(original),before,'Full-precision native result data stays untouched');
console.log('Study comparison ownership, request ordering, empty results, failures/retry and native-data preservation passed.');
