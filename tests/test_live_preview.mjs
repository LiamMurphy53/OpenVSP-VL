import assert from 'node:assert/strict';
import {latestPreview} from '../web/live-preview.js';
const calls=[],shown=[],errors=[],timers=new Map();let count=0,pending=0,current=true;
const preview=latestPreview({request:value=>new Promise((resolve,reject)=>calls.push({value,resolve,reject})),show:data=>shown.push(data),fail:error=>errors.push(error.message),pending:()=>pending++,isCurrent:()=>current,setTimer:f=>{timers.set(++count,f);return count;},clearTimer:id=>timers.delete(id)});
const flush=async()=>{await Promise.resolve();await Promise.resolve();};
preview.schedule({fraction:.1});preview.schedule({fraction:.2});
assert.equal(timers.size,1,'Continuous dragging schedules a bounded update, not an endlessly postponed debounce');
const callback=[...timers.values()][0];timers.clear();callback();
assert.deepEqual(calls[0].value,{fraction:.2});
preview.schedule({fraction:.3});preview.schedule({fraction:.9},true);
assert.equal(calls.length,1,'Only one native query runs at a time');
calls[0].resolve('obsolete');await flush();
assert.deepEqual(shown,[]);assert.deepEqual(calls[1].value,{fraction:.9},'Intermediate queued values are superseded');
preview.schedule({fraction:.9},true);calls[1].resolve('latest');await flush();
assert.deepEqual(shown,['latest']);assert.equal(calls.length,2,'Release does not duplicate the in-flight final value');
preview.schedule({fraction:.9});assert.equal(timers.size,0);
preview.schedule({fraction:.4},true);preview.invalidate();calls[2].resolve('invalidated');await flush();
assert.deepEqual(shown,['latest'],'Clearing an active input invalidates in-flight output');
preview.schedule({fraction:.5},true);calls[3].reject(Error('native failure'));await flush();
assert.deepEqual(errors,['native failure']);
preview.schedule({fraction:.5},true);assert.equal(calls.length,5,'Failed settings remain retryable');
current=false;calls[4].resolve('wrong revision');await flush();assert.deepEqual(shown,['latest']);
current=true;preview.schedule({fraction:.6});preview.dispose();assert.equal(timers.size,0);
preview.schedule({fraction:.7},true);assert.equal(calls.length,5,'Disposed views cannot issue queries');
assert.ok(pending>=6);
console.log('Latest native preview scheduling, coalescing, invalidation, failures and disposal passed.');
