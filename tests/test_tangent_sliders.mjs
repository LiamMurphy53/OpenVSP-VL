import assert from 'node:assert/strict';
import {tangentSliderParameters,tangentCoordinates,mountTangentEditor} from '../web/curve-tangent-editor.js';
const handle={point:4,coordinates:[.2,.3,0],parameters:[0,1,2].map(i=>({active:i!==2,min:-2,max:2}))};
const control={anchor:3,u:.25,smooth:true,smoothActive:true,handles:{outgoing:handle}};
const section={id:'section-a',tangentControls:[control]};
const parameters=tangentSliderParameters(section,control,'outgoing');
assert.equal(parameters.length,3);
assert.notEqual(parameters[0].customSlider.key,tangentSliderParameters({...section,id:'section-b'},control,'outgoing')[0].customSlider.key);
const inputs=handle.coordinates.map((x,i)=>({value:String(x),disabled:i===2}));
const slider={dataset:{customSlider:'tangent-0'},value:'.45',disabled:false};
const wrapper={dataset:{sliderKey:parameters[0].customSlider.key},querySelector:()=>slider,querySelectorAll:()=>[]};
const elements=new Map(['[aria-label="Tangent anchor"]','[aria-label="Driving tangent"]','[aria-label="Smooth selected tangent"]','[data-apply-tangent]','[data-tangent-status]'].map(k=>[k,{}]));
const host={innerHTML:'',querySelector:k=>elements.get(k)||inputs[Number(k.match(/id="tangent-(\d)"/)?.[1])],querySelectorAll:k=>k==='[data-tangent-axis]'?inputs:[wrapper]};
globalThis.document={getElementById:()=>null};
const calls=[];
mountTangentEditor(host,section,()=>assert.fail('Live edit should handle slider changes'),String,{isBusy:()=>false,toast:assert.fail,liveEdit:(...args)=>calls.push(args)});
assert.match(host.innerHTML,/Tangent handle X slider/);
assert.match(host.innerHTML,/Tangent handle Z slider"[^>]*disabled/);
slider.oninput();
assert.deepEqual(calls[0][2],{operation:'curve-tangent',anchor:3,side:'outgoing',xyz:[.45,.3,0]});
assert.equal(calls[0][3],false);
inputs.forEach(input=>input.disabled=true); // Application locks numeric fields during live native work.
slider.onpointerup();slider.onchange();
assert.equal(calls.length,2);assert.equal(calls[1][3],true);
assert.deepEqual(calls[1][2].xyz,[.45,.3,0],'Busy fields must retain the final slider value');
inputs[1].value='';assert.throws(()=>tangentCoordinates(inputs,handle),/finite/);
inputs[1].value='3';assert.throws(()=>tangentCoordinates(inputs,handle),/limits/);
inputs[1].value='.3';inputs[2].value='99';
assert.deepEqual(tangentCoordinates(inputs,handle),[.45,.3,0],'Locked coordinate keeps native value');
console.log('Tangent sliders: live coordinates, companion axes, locked axes, validation and one release passed.');
