import assert from 'node:assert/strict';
import {pointSliderParameters} from '../web/curve-editor.js';
import {customSliderMarkup,bindCustomSliders} from '../web/custom-sliders.js';
const points=[[.2,-.4,.7],[1,0,0]],activity=[[true,false,true],[true,true,true]];
const parameters=pointSliderParameters(points,activity,0,'profile');
assert.equal(parameters.length,2);
assert.equal(parameters[0].value,.2);
assert.equal(parameters[1].active,false);
assert.notEqual(parameters[0].customSlider.key,pointSliderParameters(points,activity,1,'profile')[0].customSlider.key);
assert.notEqual(parameters[0].customSlider.key,pointSliderParameters(points,activity,0,'other')[0].customSlider.key);
const units={esc:String,displayValue:x=>x,parameterDimension:()=>null,readOnly:p=>!p.active};
assert.match(customSliderMarkup(parameters[1],'y',units),/disabled/);
const input={value:'.2'},slider={dataset:{customSlider:'x'},value:'.25',disabled:false};
const wrapper={dataset:{sliderKey:parameters[0].customSlider.key},querySelector:()=>slider,querySelectorAll:()=>[]};
const host={querySelectorAll:()=>[wrapper],querySelector:()=>input};
const calls=[];
bindCustomSliders(host,parameters,{...units,isBusy:()=>false,liveEdit:(p,s,value,finished)=>{points[0][p.axis]=value;if(finished)calls.push([...points[0]]);}});
slider.oninput();assert.equal(points[0][0],.25);assert.equal(calls.length,0);
slider.onchange();slider.onpointerup();assert.deepEqual(calls,[[.25,-.4,.7]]);
console.log('Point sliders preserve locked axes, Z, profile identity and one commit per gesture.');
