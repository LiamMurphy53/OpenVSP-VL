import assert from 'node:assert/strict';
import {cloudPlaneCSV} from '../web/cloud-plane.js';
const points=Array.from({length:305},(_,i)=>[i+Number.EPSILON,Math.PI*(i+1),-1e-17*(i+1)]);
points[0]=[-0,Number.MIN_VALUE,Number.MAX_VALUE];
const offsets=points.map((_,i)=>i?Math.E*(i+1):-0),data={points,signedOffsets:offsets};
const text=cloudPlaneCSV(data),rows=text.trimEnd().split('\n');
assert.equal(rows[0],'Point,X,Y,Z,SignedOffset');
assert.equal(rows.length,306,'Export includes every point beyond the 200-row display limit');
for(let i=0;i<points.length;i++)assert.deepEqual(rows[i+1].split(',').map(Number),[i+1,...points[i],offsets[i]],'All finite double values round-trip, including signed zero');
console.log('Full cloud CSV rows, native numeric column order and finite-double round-trip precision pass.');
