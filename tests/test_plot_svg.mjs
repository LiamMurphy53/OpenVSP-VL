import assert from 'node:assert/strict';
import {plotSVG} from '../web/plot-svg.js';
const svg=plotSVG([1,2],[4,8],'Case <x>','CL "native"',false,null,true);
assert.match(svg,/Case &lt;x&gt;/);assert.match(svg,/CL &quot;native&quot;/);
assert.equal((svg.match(/<circle /g)||[]).length,2);
assert.doesNotMatch(svg,/NaN|Infinity/);
assert.equal(plotSVG([1],[null],'X','Y'),'<p>No numeric samples.</p>');
const gaps=plotSVG([1,2,3],[4,null,8],'X','Y');
assert.match(gaps,/d="M [^"]+ M /,'Missing samples must break connected lines');
console.log('Standalone result plots render without installed tool state and escape labels');
const {wrapPlotLabel}=await import('../web/plot-svg.js');
const label='Aircraft / very long component designation / XSec_12 / Outboard trailing edge absolute section rotation (native degrees)';
const wrapped=wrapPlotLabel(label);
assert.ok(wrapped.length>1);assert.equal(wrapped.join(' '),label);
assert.ok(wrapped.every(line=>Array.from(line).length<=48));
assert.equal(wrapPlotLabel('x'.repeat(145)).join(''),'x'.repeat(145));
assert.ok(wrapPlotLabel('翼'.repeat(100)).every(line=>Array.from(line).length<=48));
const long=plotSVG([15,25],[77.64505836954598,89.63578804402714],label,label,false,null,true);
assert.match(long,/xmlns="http:\/\/www.w3.org\/2000\/svg"/);
assert.match(long,/style="font:11px system-ui,sans-serif;fill:#53614e;height:auto"/);
assert.match(long,/<tspan /);assert.match(long,new RegExp(`<title>${label.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}</title>`));
assert.ok(Number(long.match(/height="([\d.]+)"/)[1])>310,'Both labels receive their own space outside the data region');
assert.match(long,/<title>[^<]*77\.64505836954598<\/title>/);
const scientific=plotSVG([1e-30,2e-30],[1.000000000001,1.000000000002],'X','Y',false,null,true);
assert.doesNotMatch(scientific,/NaN|Infinity/);
assert.ok(Number(scientific.match(/width="([\d.]+)"/)[1])>620,'Scientific tick labels get a larger left margin');
console.log('Exported plots retain fonts, namespaces, full wrapped labels, native precision and scientific tick margins.');
