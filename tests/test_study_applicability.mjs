import assert from 'node:assert/strict';
import {studyRuleApplies} from '../web/study-applicability.js';
import {collectAnalysisInputs} from '../web/analysis-input-state.js';
const rule={input:'BoundaryType',values:[2]},host={getElementById:id=>({'s-BoundaryType-0':{value:'0'},'s-Limit-0':{value:'',dataset:{scalar:'true'},tagName:'INPUT'}}[id])};
const axis={kind:'input',stage:0,name:'BoundaryType',values:[0,2]};
const applies=(r=rule,axes=[axis],stage=0,kind='input',member=null)=>studyRuleApplies(r,axes,stage,kind,'s',host,member);
assert.equal(applies(),true);
assert.equal(applies(rule,[{...axis,values:[0]}]),false);
assert.equal(applies(rule,[],1),false);
assert.equal(applies(rule,[axis],1),false);
assert.equal(applies(rule,[axis],0,'geometryInput'),false);
assert.equal(applies(rule,[{...axis,member:'a'}]),false);
assert.equal(applies(rule,[{...axis,member:'a'}],0,'input','a'),true);
assert.equal(applies(rule,[{...axis,valueMode:'array',values:[[0],[2]]}]),true);
assert.equal(applies(rule,[{...axis,element:1}]),false);
assert.equal(applies({all:[rule,{input:'BoundaryType',values:[0]}]}),false,'One controller cannot be 0 and 2 in one case');
assert.equal(applies({any:[rule,{input:'BoundaryType',values:[1]}]}),true);
const spec={inputs:[{name:'Limit',index:0,type:2,values:[3],editable:true,applicableWhen:rule}]};
assert.throws(()=>collectAnalysisInputs(spec,'s',host,false,true,r=>applies(r)),/finite|number|empty/i,'Future-active incomplete field must be validated');
assert.deepEqual(collectAnalysisInputs(spec,'s',host,false,true,r=>applies(r,[])),[]);
console.log('Study visibility follows matching sweep cases, correlations and input validation.');
assert.equal(applies(rule,[axis],0,'input','a'),true,'A shared assembly controller sweep applies to each member');
assert.equal(applies(rule,[{...axis,member:'b'}],0,'input','a'),false,'A different member stays independent');
