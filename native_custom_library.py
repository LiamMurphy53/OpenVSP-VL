"""Guidance for the official bundled .vsppart component library."""
TYPES={'Box','BoxGroup','Duct','Disk','Cone','TransportFuse','OnOffExample'}
LENGTHS={'Length','Width','Height','Diameter','Chord','GapRow','GapCol'}
LABELS={'SquareFlag':'Cube dimensions','NumRow':'Rows','NumCol':'Columns','GapRow':'Row spacing','GapCol':'Column spacing','BoxLayout':'Array preset','LayoutTrigger':'Apply array preset','Shape':'Duct maximum-width location','ThickChord':'Thickness / chord','Camber':'Camber / chord','CamberLoc':'Camber location / chord','InvertFlag':'Invert airfoil','NoseMult':'Nose length / diameter','AftMult':'Tail length / diameter','NoseCenter':'Nose center offset','AftCenter':'Tail center offset','AftWidth':'Tail width factor','AftHeight':'Tail height factor','OnOffFlag':'Generate geometry'}


def enrich(v,gid,params):
    if v.GetGeomTypeName(gid) not in TYPES and v.GetGeomTypeName(gid)!='Custom' and not v.GetGeomTypeName(gid).startswith('StudioPart_'):return
    square=next((pid for pid in v.GetGeomParmIDs(gid) if v.GetParmGroupName(pid)=='Design' and v.GetParmName(pid)=='SquareFlag'),None)
    for p in params:
        if p['rawGroup']=='Design':
            p['label']=LABELS.get(p['name'],p['name'])
            if p['name'] in LENGTHS:p['dimension']='length'
            if p['name']=='LayoutTrigger':p['trigger']=True
            if p['name']=='BoxLayout':p['choices']=[[0,'2 × 2'],[1,'2 × 4'],[2,'4 × 2']]
            if p['description'] in ('Default Description','Custom Descript'):p['description']=''
            if square and v.ValidParm(square) and v.GetParmVal(square) and p['name'] in ('Width','Height'):
                p.update(displayReadOnly=True,readOnlyReason='Follows Length while cube dimensions are enabled.')
        elif p['rawGroup'] in ('XSec','XSecCurve','Close','Trim','Flap','Chevron'):
            p.update(displayReadOnly=True,readOnlyReason='Generated by the native library script. Edit this component’s Design dimensions.')

    from native_custom_scripts import gui_definitions,gui_updates
    definitions=gui_definitions(v,gid)
    import native_custom_layout
    layout=native_custom_layout.contexts(v,definitions)
    updates=gui_updates(v,gid)
    bindings={u['index']:u['parameterId'] for u in updates}
    previous={u['index']:u['parameterId'] for u in updates if u['parameterId']}
    bound_ids={pid for pid in bindings.values() if pid}
    by_id={p['id']:p for p in params}
    by_key={(p['rawGroup'],p['name']):p for p in params}
    choice=None
    tab=None
    tab_index=None
    for definition in definitions:
        kind=definition['type']
        if kind in (v.GDEV_TAB,v.GDEV_SCROLL_TAB):
            tab=definition['label'] or None
            tab_index=definition['index']
            choice=None
            continue
        original=by_key.get((definition['group'],definition['parameter'])) or by_id.get(previous.get(definition['index']))
        if original and definition['index'] in bindings and original['id'] not in bound_ids:
            original.update(displayReadOnly=True,readOnlyReason='Disconnected by the custom script in this configuration.')
        mapped=by_id.get(bindings.get(definition['index'])) if definition['index'] in bindings else original
        if mapped is None and original:
            original['customControl']=True
            native_custom_layout.annotate(original,definition,layout)
            if tab:original.update(customTab=tab,customTabIndex=tab_index,group=tab)
            if original['name'] in LABELS:original['label']=LABELS[original['name']]
            if original['name'] in LENGTHS:original['dimension']='length'
            if original['description'] in ('Default Description','Custom Descript'):original['description']=''
        if kind==v.GDEV_ADD_CHOICE_ITEM:
            if choice is not None:choice['choices'].append([len(choice['choices']),definition['label']])
            continue
        if kind==v.GDEV_CHOICE:
            choice=mapped
            if choice is not None:choice['choices']=[]
        p=mapped
        if p is None:continue
        p['customControl']=True
        native_custom_layout.annotate(p,definition,layout)
        if tab:p.update(customTab=tab,customTabIndex=tab_index,group=tab)
        if p['name'] in LABELS:p['label']=LABELS[p['name']]
        if p['name'] in LENGTHS:p['dimension']='length'
        if p['description'] in ('Default Description','Custom Descript'):p['description']=''
        if definition['label'] and p['name'] not in LABELS:p['label']=definition['label'].rstrip(':')
        if kind==v.GDEV_INDEX_SELECTOR:p['customIndexSelector']=definition['index']
        if kind==v.GDEV_PARM_BUTTON:p['customParmButton']=True
        if kind in (v.GDEV_SLIDER_INPUT,v.GDEV_SLIDER_ADJ_RANGE_INPUT):
            p['customSlider']=dict(range=definition.get('range'),adjustable=kind==v.GDEV_SLIDER_ADJ_RANGE_INPUT,
                                   key=f'{gid}:{definition["index"]}:{p["id"]}')
        if kind==v.GDEV_OUTPUT:p.update(displayReadOnly=True,readOnlyReason='Calculated output from the custom script.')
        if kind==v.GDEV_TRIGGER_BUTTON:
            p['trigger']=True
            p['triggerLabel']=p.get('label') or definition['label'] or 'Apply'


def validate(v,pid):
    from native_worker import parameter
    owner=next((g for g in v.FindGeoms() if (v.GetGeomTypeName(g) in (TYPES|{'Custom'}) or v.GetGeomTypeName(g).startswith('StudioPart_')) and pid in v.GetGeomParmIDs(g)),None)
    if not owner:return
    p=parameter(v,pid);enrich(v,owner,[p])
    if p.get('displayReadOnly'):raise ValueError(p['readOnlyReason'])


def validate_gui(v):
    """Evaluate script control bindings before committing the native file."""
    from native_custom_scripts import gui_updates
    for gid in v.FindGeoms():
        kind=v.GetGeomTypeName(gid)
        if kind in TYPES or kind=='Custom' or kind.startswith('StudioPart_'):gui_updates(v,gid)


def is_custom(v,gid):
    kind=v.GetGeomTypeName(gid)
    return kind in TYPES or kind=='Custom' or kind.startswith('StudioPart_')


def validate_surfaces(v,gid=None):
    from native_custom_scripts import surface_topology
    for g in ([gid] if gid else v.FindGeoms()):
        if not is_custom(v,g):continue
        for surface in surface_topology(v,g):
            if surface['uPatches']<=0 or surface['wPatches']<=0:
                raise ValueError(f'{v.GetGeomName(g)}: custom script did not produce a valid native surface {surface["index"]}. Check its profile compatibility and SkinXSecSurf call. The edit was not saved.')
